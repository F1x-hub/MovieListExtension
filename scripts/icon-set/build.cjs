'use strict';

/**
 * Writes the drawings of icons.cjs wherever they are used:
 *   - the generated block of src/shared/utils/Icons.js;
 *   - the body of every <svg data-icon="NAME"> in src and content-scripts, so an icon in
 *     markup is there from the first paint and still has one source.
 *
 *   node scripts/icon-set/build.cjs          writes
 *   node scripts/icon-set/build.cjs --check  fails when something is out of date
 */

const fs = require('node:fs');
const path = require('node:path');
const icons = require('./icons.cjs');

const ROOT = path.join(__dirname, '../..');
const ICONS_JS = path.join(ROOT, 'src/shared/utils/Icons.js');
const BEGIN = '    // <icon-set> generated by scripts/icon-set/build.cjs, do not edit by hand';
const END = '    // </icon-set>';
const INLINE = /(<svg\b[^>]*\bdata-icon="([A-Z0-9_]+)"[^>]*>)[\s\S]*?(<\/svg>)/g;

// Where the set is used from script: posters without a picture are larger than 20px,
// marks beside text are smaller.
const SIZES = { MOVIE_CLAPPER: 40, CHEVRON_DOWN: 14, CHEVRON_UP: 14, CLOSE: 16, PLUS: 16, CHECK: 16, MORE_VERTICAL: 16 };

function iconsBlock() {
    const entries = Object.entries(icons).map(([name, body]) => {
        const size = SIZES[name] || 20;
        return `    ${name}: '<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 20 20" fill="none" aria-hidden="true" focusable="false">${body}</svg>',`;
    });
    return [BEGIN, ...entries, END].join('\n');
}

function withBlock(source) {
    const from = source.indexOf(BEGIN);
    const to = source.indexOf(END);
    if (from < 0 || to < from) throw new Error('Icons.js has no <icon-set> block');
    return source.slice(0, from) + iconsBlock() + source.slice(to + END.length);
}

function withInline(source, file) {
    return source.replace(INLINE, (match, open, name, close) => {
        if (!icons[name]) throw new Error(`${file}: unknown icon ${name}`);
        if (!open.includes('viewBox="0 0 20 20"') || !open.includes('fill="none"')) throw new Error(`${file}: ${name} needs viewBox="0 0 20 20" and fill="none"`);
        return open + icons[name] + close;
    });
}

function sources() {
    return ['src', 'content-scripts']
        .flatMap(dir => fs.readdirSync(path.join(ROOT, dir), { recursive: true }).map(file => path.join(ROOT, dir, String(file))))
        .filter(file => /\.(html|js)$/.test(file) && file !== ICONS_JS);
}

const changed = [];
const uses = {};

function update(file, next, source) {
    if (next === source) return;
    changed.push(path.relative(ROOT, file));
    if (!process.argv.includes('--check')) fs.writeFileSync(file, next);
}

const iconsSource = fs.readFileSync(ICONS_JS, 'utf8');
update(ICONS_JS, withBlock(iconsSource), iconsSource);

for (const file of sources()) {
    const source = fs.readFileSync(file, 'utf8');
    if (!source.includes('data-icon="')) continue;
    for (const [, , name] of source.matchAll(INLINE)) uses[name] = (uses[name] || 0) + 1;
    update(file, withInline(source, path.relative(ROOT, file)), source);
}

const total = Object.values(uses).reduce((sum, count) => sum + count, 0);
const summary = `${Object.keys(icons).length} icons, ${total} uses in markup`;
if (process.argv.includes('--check')) {
    if (changed.length) {
        console.error(`Out of date, run node scripts/icon-set/build.cjs:\n${changed.join('\n')}`);
        process.exit(1);
    }
    console.log(`Up to date: ${summary}`);
} else {
    console.log(`${summary}; wrote ${changed.length} files`);
}
