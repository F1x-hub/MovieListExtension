#!/usr/bin/env node
/**
 * Generates src/shared/data/worldMap.js: the world map of the profile's «Страны» section as
 * ready SVG paths, so the extension ships no map library and makes no request for it.
 *
 * Source: world-atlas 2.0.2 (Natural Earth 1:110m, public domain), projected with d3-geo's
 * Natural Earth projection rotated 11° east, so the antimeridian cut runs past Chukotka and
 * Russia and Fiji stay whole. Each shape gets its ISO alpha-2 code from its English name.
 * Countries too small for this scale get a point to draw a small square at.
 *
 *   node scripts/build-world-map.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { geoNaturalEarth1, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';
import { countryCode } from '../src/shared/data/countries.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const topology = JSON.parse(fs.readFileSync(path.join(root, 'node_modules/world-atlas/countries-110m.json'), 'utf8'));
const OUTPUT = path.join(root, 'src/shared/data/worldMap.js');

// Natural Earth's short names the browser does not know.
const NAMES = {
    'Dem. Rep. Congo': 'CD', 'Central African Rep.': 'CF', 'Bosnia and Herz.': 'BA', 'Dominican Rep.': 'DO',
    'Eq. Guinea': 'GQ', 'S. Sudan': 'SS', 'Solomon Is.': 'SB', 'Falkland Is.': 'FK', 'Fr. S. Antarctic Lands': 'TF',
    'W. Sahara': 'EH', 'eSwatini': 'SZ', "Côte d'Ivoire": 'CI', 'Timor-Leste': 'TL', 'Macedonia': 'MK',
    'Czechia': 'CZ', 'Palestine': 'PS', 'Kosovo': 'XK', 'Greenland': 'GL', 'Puerto Rico': 'PR', 'New Caledonia': 'NC',
    'Vanuatu': 'VU', 'Brunei': 'BN', 'Laos': 'LA', 'North Korea': 'KP', 'South Korea': 'KR', 'Taiwan': 'TW'
};
// Shapes with no country of their own: drawn, never coloured.
const NO_CODE = new Set(['N. Cyprus', 'Somaliland']);
// [longitude, latitude] of countries and territories the 110m outlines leave out.
const SMALL = {
    HK: [114.17, 22.32], MO: [113.54, 22.19], SG: [103.82, 1.35], MT: [14.45, 35.9], MC: [7.42, 43.74],
    AD: [1.52, 42.51], LI: [9.55, 47.17], SM: [12.46, 43.94], VA: [12.45, 41.9], BH: [50.56, 26.07],
    MV: [73.5, 4.18], BB: [-59.54, 13.19], MU: [57.55, -20.35], SC: [55.49, -4.68], CV: [-23.6, 15.1],
    KM: [43.87, -11.88], WS: [-172.1, -13.76], TO: [-175.2, -21.18], DM: [-61.37, 15.41], LC: [-60.98, 13.91],
    AG: [-61.8, 17.06], KN: [-62.78, 17.36], VC: [-61.2, 13.25], GD: [-61.68, 12.12], MH: [171.18, 7.13],
    FM: [158.22, 6.92], PW: [134.58, 7.51], NR: [166.93, -0.52], TV: [179.2, -8.52], KI: [-157.36, 1.87],
    ST: [6.61, 0.19], GU: [144.79, 13.44], AW: [-69.97, 12.52], CW: [-68.99, 12.17], BM: [-64.75, 32.31],
    KY: [-81.25, 19.31], MQ: [-61.02, 14.64], GP: [-61.55, 16.25], RE: [55.54, -21.12], PF: [-149.41, -17.65],
    FO: [-6.91, 61.89], GI: [-5.35, 36.14], IM: [-4.55, 54.24], JE: [-2.13, 49.21], GG: [-2.59, 49.46]
};

const shapes = feature(topology, topology.objects.countries).features.filter(shape => shape.id !== '010');
const projection = geoNaturalEarth1().rotate([-11, 0]).fitExtent([[4, 4], [956, 476]], { type: 'FeatureCollection', features: shapes });
const draw = geoPath(projection).digits(1);

const unmatched = [];
const countries = shapes.map(shape => {
    const name = shape.properties.name;
    const code = NO_CODE.has(name) ? null : NAMES[name] || countryCode(name);
    if (!code && !NO_CODE.has(name)) unmatched.push(name);
    return { code, d: draw(shape) };
});
if (unmatched.length) throw new Error(`No ISO code for: ${unmatched.join(', ')}`);
const codes = countries.map(country => country.code).filter(Boolean);
const duplicates = codes.filter((code, index) => codes.indexOf(code) !== index);
if (duplicates.length) throw new Error(`One code for two shapes: ${duplicates.join(', ')}`);
const small = Object.fromEntries(Object.entries(SMALL)
    .filter(([code]) => !codes.includes(code))
    .map(([code, point]) => [code, projection(point).map(value => Math.round(value * 10) / 10)]));

const data = { viewBox: '0 0 960 480', countries, small };
fs.writeFileSync(OUTPUT, `// Generated by scripts/build-world-map.mjs from world-atlas 2.0.2 (Natural Earth 1:110m,
// public domain). Do not edit by hand: change the script and run it again.
export const WORLD_MAP = Object.freeze(${JSON.stringify(data)});
`);
console.log(`worldMap.js: ${countries.length} shapes, ${codes.length} with a code, ${Object.keys(small).length} small countries, ${fs.statSync(OUTPUT).size} bytes`);
