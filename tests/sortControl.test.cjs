const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');

async function main() {
    const dom = new JSDOM('<body><label for="sort">Сортировка</label><select id="sort"><option value="new">Дата добавления (Сначала новые)</option><option value="old">Дата добавления (Сначала старые)</option><option value="disabled" disabled>Недоступно</option><option value="title">Название (А–Я)</option></select><button id="next">Далее</button></body>', { runScripts: 'outside-only', pretendToBeVisual: true });
    const { window } = dom;
    const { document } = window;
    window.eval(fs.readFileSync(path.resolve(__dirname, '../src/shared/components/SortControl.js'), 'utf8'));
    const select = document.querySelector('select');
    const control = window.SortControl.enhance(select);
    control.trigger.getBoundingClientRect = () => ({ top: 40, bottom: 84, left: 40, right: 300, width: 260, height: 44 });
    const key = keyName => {
        const event = new window.KeyboardEvent('keydown', { key: keyName, bubbles: true, cancelable: true });
        control.trigger.dispatchEvent(event);
        return event;
    };
    let changes = 0;
    let bubbled = 0;
    select.addEventListener('change', () => changes++);
    document.body.addEventListener('change', () => bubbled++);
    assert.equal(window.SortControl.enhance(select), control, 'enhancement is idempotent');
    assert.equal(select.hidden, true);
    assert.equal(control.trigger.getAttribute('role'), 'combobox');
    assert.ok(control.trigger.getAttribute('aria-labelledby').includes(document.querySelector('label').id));
    assert.equal(control.list.getAttribute('aria-labelledby'), document.querySelector('label').id, 'listbox has visible-label name');
    assert.equal(control.valueLabel.textContent, select.options[0].textContent, 'full label is preserved');
    document.querySelector('label').click();
    assert.equal(document.activeElement, control.trigger, 'visible native label focuses enhanced control');

    key('Enter');
    assert.equal(control.isOpen, true);
    assert.equal(document.activeElement, control.trigger, 'list never steals focus');
    assert.equal(control.list.parentElement, document.body, 'popup is portalled');
    key('ArrowDown');
    assert.equal(select.value, 'new', 'navigation is pending');
    key('Escape');
    assert.equal(select.value, 'new', 'Escape cancels');
    assert.equal(changes, 0);
    assert.equal(control.isOpen, false);
    key(' ');
    key('ArrowDown');
    key('Enter');
    assert.equal(select.value, 'old');
    assert.equal(changes, 1);
    assert.equal(bubbled, 1);
    key('Enter');
    key('Enter');
    assert.equal(changes, 1, 'reselecting committed option emits nothing');

    key('Enter');
    key('ArrowDown');
    assert.equal(control.activeIndex, 3, 'navigation skips disabled option');
    assert.equal(key('Tab').defaultPrevented, false, 'Tab keeps normal focus traversal');
    assert.equal(select.value, 'title', 'Tab commits pending choice');
    assert.equal(control.isOpen, false);
    assert.equal(changes, 2);
    control.open();
    key('Home');
    key('н');
    assert.equal(control.activeIndex, 3, 'typeahead uses localized option text');
    control.close();

    select.value = 'new';
    control.syncFromNative();
    assert.equal(control.valueLabel.textContent, select.options[0].textContent);
    assert.equal(changes, 2, 'native sync never dispatches');
    assert.equal(control.setValue('missing', { emit: true }), false);
    assert.equal(select.value, 'new');
    control.setValue('old');
    assert.equal(changes, 2, 'setValue defaults to silent');
    control.setOptions([{ value: 'old', label: '<b>Старые</b>' }, { value: 'new', label: 'Новые', labelKey: 'sort.new' }]);
    assert.equal(select.value, 'old', 'setOptions retains valid selection');
    assert.equal(control.list.querySelector('b'), null, 'labels are text');
    assert.equal(select.options[1].dataset.i18n, 'sort.new');
    control.open();
    control.list.children[1].dispatchEvent(new window.MouseEvent('click', { bubbles: true }));
    assert.equal(select.value, 'new');
    assert.equal(changes, 3, 'pointer selection emits exactly once');

    select.options[1].textContent = 'Newest';
    await new Promise(resolve => window.setTimeout(resolve, 0));
    assert.equal(control.valueLabel.textContent, 'Newest', 'locale mutation updates presentation');
    control.open();
    select.disabled = true;
    await new Promise(resolve => window.setTimeout(resolve, 0));
    assert.equal(control.trigger.disabled, true);
    assert.equal(control.isOpen, false, 'disabling closes popup');
    control.open();
    assert.equal(control.isOpen, false);
    control.setDisabled(true, 'Сортировка недоступна при поиске');
    assert.equal(control.hint.hidden, false);
    assert.ok(control.trigger.getAttribute('aria-describedby').includes(control.hint.id));
    control.setDisabled(false);
    assert.equal(control.hint.hidden, true);

    const secondSelect = document.createElement('select');
    secondSelect.innerHTML = '<option value="a">A</option>';
    document.body.append(secondSelect);
    const second = window.SortControl.enhance(secondSelect);
    second.trigger.getBoundingClientRect = control.trigger.getBoundingClientRect;
    control.open();
    second.open();
    assert.equal(control.isOpen, false, 'only one popup can be open');
    document.body.dispatchEvent(new window.Event('pointerdown', { bubbles: true }));
    assert.equal(second.isOpen, false, 'outside pointer closes');
    control.open();
    control.trigger.getBoundingClientRect = () => ({ top: -60, bottom: -16, left: 40, right: 300, width: 260 });
    window.dispatchEvent(new window.Event('resize'));
    assert.equal(control.isOpen, false, 'offscreen anchor closes popup');

    const oldTrigger = control.trigger;
    control.destroy();
    assert.equal(select.hidden, false);
    assert.equal(select.getAttribute('tabindex'), null);
    assert.equal(control.list.isConnected, false);
    oldTrigger.click();
    assert.equal(control.isOpen, false, 'destroy removes listeners');
    select.options[0].textContent = 'Changed after destroy';
    await new Promise(resolve => window.setTimeout(resolve, 0));
    assert.equal(control.valueLabel.textContent, 'Newest', 'destroy disconnects observer');
    second.destroy();
    const dialog = document.createElement('div');
    dialog.setAttribute('role', 'dialog');
    dialog.setAttribute('aria-modal', 'true');
    dialog.innerHTML = '<label><span>Сортировка раздач</span><select><option value="seeds">Сиды: больше</option><option value="size">Размер: меньше</option></select></label>';
    document.body.append(dialog);
    const torrentSelect = dialog.querySelector('select');
    const torrentControl = window.SortControl.enhance(torrentSelect);
    const caption = dialog.querySelector('label > span');
    assert.equal(torrentControl.list.parentElement, dialog, 'modal popup stays inside its accessible modal scope');
    assert.equal(torrentControl.list.getAttribute('aria-labelledby'), caption.id, 'wrapped label uses caption only');
    assert.equal(torrentControl.trigger.getAttribute('aria-labelledby'), `${caption.id} ${torrentControl.trigger.id}`);
    assert.equal(dialog.querySelector('label').id, '', 'wrapping label is never used as recursive name');
    let documentScrollCalls = 0;
    window.HTMLElement.prototype.scrollIntoView = () => { documentScrollCalls++; };
    torrentControl.trigger.getBoundingClientRect = () => ({ top: 40, bottom: 84, left: 40, right: 300, width: 260 });
    Object.defineProperty(torrentControl.list, 'clientHeight', { value: 44 });
    torrentControl.open();
    Object.defineProperty(torrentControl.list.children[1], 'offsetTop', { value: 44 });
    Object.defineProperty(torrentControl.list.children[1], 'offsetHeight', { value: 44 });
    torrentControl.setActive(1);
    assert.equal(documentScrollCalls, 0, 'active navigation never scrolls document ancestors');
    assert.equal(torrentControl.list.scrollTop, 44, 'only popup scroll position follows active option');
    torrentControl.destroy();
    const css = fs.readFileSync(path.resolve(__dirname, '../src/shared/styles/components.css'), 'utf8');
    const valueRule = css.match(/\.sort-control__value\s*\{([^}]+)\}/)[1];
    assert.match(valueRule, /white-space:\s*normal/);
    assert.match(valueRule, /overflow-wrap:\s*anywhere/);
    assert.doesNotMatch(valueRule, /ellipsis|nowrap/);
    assert.match(css, /\.sort-control__trigger\s*\{[^}]*min-height:\s*44px/s);
    dom.window.close();
    console.log('SortControl: interaction, sync, cleanup and readability checks passed');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
