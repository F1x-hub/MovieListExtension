const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const dom = new JSDOM('<div><span>Источник</span><div id="sourceButtonsContainer"></div><button id="outside">Outside</button></div>', { runScripts: 'outside-only' });
const w = dom.window;
for (const file of ['src/pages/movie-details/WatchEntryController.js', 'src/shared/services/player/WatchSourcePolicy.js']) {
    w.eval(fs.readFileSync(path.join(__dirname, '..', file), 'utf8'));
}
(async () => {
    const container = w.document.getElementById('sourceButtonsContainer');
    const value = 'https://example.com/player?q="][data-value="evil';
    const add = (value, label) => {
        const button = w.document.createElement('button'); button.className = 'source-btn';
        button.dataset.value = value; button.textContent = label; container.append(button); return button;
    };
    const original = add(value, 'Provider');
    add('parser:animego', 'AnimeGo');
    let delegated = 0;
    container.addEventListener('click', () => delegated++);
    const watched = [];
    let torrents = 0;
    const control = new w.WatchEntryController({ container, onWatch: value => watched.push(value), onTorrent: () => torrents++ });
    control.sync(value, { torrentEligible: true });
    assert.equal(w.document.querySelector('#sourcePopover #sourceButtonsContainer'), container);
    assert.equal(container.firstChild, original);
    assert.equal(control.watch.dataset.aliasValue, value);
    assert.equal(control.watch.hasAttribute('data-value'), false);
    assert.equal(control.watch.classList.contains('source-btn'), false);
    assert.equal(control.watch.hasAttribute('aria-haspopup'), false);
    control.watch.click(); assert.deepEqual(watched, [value]);
    control.toggle.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'ArrowDown', bubbles: true }));
    assert.equal(control.toggle.getAttribute('aria-expanded'), 'true');
    assert.equal(w.document.activeElement, original);
    original.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'ArrowDown', bubbles: true }));
    assert.equal(w.document.activeElement.dataset.value, 'parser:animego');
    control.beforeRebuild();
    container.replaceChildren(); add(value, 'Provider'); const replacement = add('parser:animego', 'AnimeGo');
    control.sync(value); assert.equal(w.document.activeElement, replacement);
    replacement.click(); assert.equal(delegated, 1);
    assert.equal(control.popover.hidden, true); assert.equal(w.document.activeElement, control.toggle);
    control.open();
    control.group.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
    assert.equal(control.popover.hidden, true);
    control.sync('mediaplayer:torrent', { torrentEligible: true, busy: true });
    assert.equal(control.watch.dataset.aliasValue, value);
    assert.equal(control.watch.getAttribute('aria-busy'), 'true');
    assert.equal(control.torrent.getAttribute('aria-pressed'), 'true');
    control.torrent.click(); assert.equal(torrents, 1);
    control.sync(value, { torrentEligible: true, sourceLocked: true });
    assert.equal(control.toggle.disabled, true); assert.equal(control.torrent.disabled, true);
    control.sync(value, { torrentEligible: true });
    control.open(); w.document.getElementById('outside').focus(); assert.equal(control.popover.hidden, true);
    control.destroy(); assert.equal(container.parentElement.id, '');
    assert.equal(w.document.getElementById('watchEntryGroup'), null);
    control.ensure(); control.sync('parser:animego'); control.watch.click();
    assert.equal(watched.length, 2, 'destroy/re-enable has one handler per action');
    control.destroy();

    const policy = w.WatchSourcePolicy;
    const values = ['parser:rutube', 'parser:exfs', 'parser:animego', 'mediaplayer:torrent', value];
    const plain = object => JSON.parse(JSON.stringify(object));
    assert.deepEqual(plain(policy.rank(values, { anime: true })), ['parser:animego', 'parser:rutube', 'parser:exfs', value]);
    assert.deepEqual(plain(policy.rank(values, { film: true })), ['parser:exfs', 'parser:animego', value, 'parser:rutube']);
    assert.equal(policy.select(values, { room: value, explicit: 'parser:exfs', preference: 'parser:animego', last: 'parser:rutube' }), value);
    assert.equal(policy.select(values, { explicit: 'parser:exfs', preference: 'parser:animego', last: 'parser:rutube' }), 'parser:exfs');
    assert.equal(policy.select(values, { preference: 'parser:animego', last: 'parser:rutube' }), 'parser:animego');
    assert.equal(policy.select(values, { last: value }), value);
    const data = {};
    w.chrome = { storage: { local: { get: async () => data, set: async payload => Object.assign(data, payload) } } };
    await policy.save(42, value); assert.equal(await policy.read(42), value);
    await policy.save(42, 'mediaplayer:torrent'); assert.equal(await policy.read(42), value);
    control.destroy();
    console.log('Watch entry: alias/dataset, keyboard/focus, original delegation, torrent, cleanup and source preference priority passed.');
} )().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => w.close());
