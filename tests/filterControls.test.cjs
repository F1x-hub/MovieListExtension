const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');

const dom = new JSDOM('<body><div id="group"></div><div id="range"><input id="from" type="range" min="1" max="10" step="0.1" value="7"><input id="to" type="range" min="1" max="10" step="0.1" value="10"><div id="bar"></div></div><span id="fromDisplay"></span><span id="toDisplay"></span><div id="numbers"><input id="yearFrom" type="number" min="1900" max="2030"><input id="yearTo" type="number" min="1900" max="2030"></div></body>', { runScripts: 'outside-only' });
const { window } = dom;
const { document } = window;
window.eval(fs.readFileSync(path.resolve(__dirname, '../src/shared/components/FilterControls.js'), 'utf8'));
const { FilterChoice, RangeControl } = window;
const fire = (element, type) => element.dispatchEvent(new window.Event(type, { bubbles: true }));

let stateCallbacks = 0;
let bubbledChanges = 0;
const group = document.getElementById('group');
group.addEventListener('change', () => bubbledChanges++);
const choice = FilterChoice.create({ label: 'Драма', value: 'drama', id: '18', className: 'tag-btn checkbox-item', labels: { neutral: 'Any', include: 'Include', exclude: 'Exclude' }, onChange: () => stateCallbacks++ });
group.append(choice);
assert.equal(choice.tagName, 'BUTTON');
assert.equal(choice.type, 'button');
assert.equal(choice.querySelector('b'), null, 'labels are text only');
assert.equal(choice.getAttribute('aria-label'), 'Драма', 'toggle name stays stable across states');
assert.equal(choice.dataset.filterValue, 'drama');
assert.equal(choice.dataset.filterId, '18');
for (const state of ['include', 'exclude', 'neutral']) {
    choice.click();
    assert.equal(choice.dataset.state, state);
    assert.equal(choice.dataset.filterState, state);
    assert.equal(choice.getAttribute('aria-pressed'), String(state !== 'neutral'));
    assert.equal(choice.getAttribute('aria-label'), 'Драма');
    assert.equal(choice.classList.contains('state-include'), state === 'include');
    assert.equal(choice.classList.contains('filter-exclude'), state === 'exclude');
}
assert.equal(stateCallbacks, 3);
assert.equal(bubbledChanges, 3);
FilterChoice.setState(choice, 'include');
assert.equal(bubbledChanges, 3, 'restoring states is silent');
FilterChoice.setState(choice, 'include', { emit: true });
assert.equal(bubbledChanges, 3, 'same state is not emitted twice');
assert.equal(choice.querySelector('.tag-status-icon').textContent, '✓');
assert.equal(choice.getAttribute('aria-label'), 'Драма');
choice.disabled = true;
choice.click();
assert.equal(choice.dataset.state, 'include', 'disabled buttons cannot cycle');
choice.disabled = false;
FilterChoice.enhanceGroup(group, { label: 'Genres', labels: { neutral: 'Any', include: 'Include', exclude: 'Exclude' } });
const legend = group.querySelector('.filter-choices__legend');
assert.match(legend.textContent, /^Any.*Include.*Exclude$/);
assert.equal(group.getAttribute('role'), 'group');
const stateDescription = document.getElementById(choice.getAttribute('aria-describedby'));
assert.ok(stateDescription);
assert.equal(stateDescription.textContent, 'Include');
choice.click();
assert.equal(stateDescription.textContent, 'Exclude', 'state is described separately from the stable toggle name');
assert.equal(group.querySelector('.filter-choices__status').textContent, 'Драма: Exclude', 'live region announces activated tri-state changes');
FilterChoice.enhanceGroup(group, {
    label: 'Жанры', labels: { neutral: 'Без предпочтений. Нажмите, чтобы включить.', include: 'Включено. Нажмите, чтобы исключить.', exclude: 'Исключено. Нажмите, чтобы сбросить.' },
    legendLabels: { neutral: 'Нейтрально', include: 'Включено', exclude: 'Исключено' }
});
assert.equal(group.querySelectorAll('.filter-choices__legend').length, 1);
assert.match(legend.textContent, /^Нейтрально.*Включено.*Исключено$/);
assert.equal(choice.getAttribute('aria-label'), 'Драма', 'localized state text does not replace the stable name');
assert.match(stateDescription.textContent, /Исключено\. Нажмите, чтобы сбросить\./);
group.replaceChildren(choice);
FilterChoice.enhanceGroup(group, { label: 'Genres' });
assert.equal(group.querySelectorAll('.filter-choices__legend').length, 1, 'legend restored after page rerender');
const detachedGroup = document.createElement('div');
FilterChoice.enhanceGroup(detachedGroup);
FilterChoice.enhanceGroup(detachedGroup);
assert.equal(detachedGroup.querySelectorAll('.filter-choices__legend').length, 1, 'detached enhancement is idempotent');

const singleGroup = document.createElement('nav');
const compactGroup = document.createElement('div');
const compactChoices = Array.from({ length: 10 }, (_, index) => FilterChoice.create({ label: `Genre ${index}`, value: index }));
compactGroup.append(...compactChoices);
FilterChoice.enhanceGroup(compactGroup, { compactLimit: 6, moreLabel: 'More ({count})', lessLabel: 'Less' });
const disclosure = compactGroup.querySelector('.filter-choices__more');
assert.equal(disclosure.textContent, 'More (4)');
assert.equal(disclosure.getAttribute('aria-controls'), compactGroup.id);
assert.equal(disclosure.getAttribute('aria-expanded'), 'false');
assert.equal(compactGroup.querySelectorAll('[data-filter-overflow]').length, 4);
disclosure.click();
assert.equal(disclosure.getAttribute('aria-expanded'), 'true');
assert.equal(disclosure.textContent, 'Less');
assert.ok(compactChoices.every(choice => choice.dataset.state === 'neutral'), 'Disclosure does not change filter values');
FilterChoice.setState(compactChoices[9], 'include');
disclosure.click();
assert.equal(disclosure.textContent, 'More (3)', 'Active overflow choices remain visible and leave the hidden count');
FilterChoice.enhanceGroup(compactGroup, { compactLimit: 6, moreLabel: 'Ещё ({count})', lessLabel: 'Свернуть' });
assert.equal(compactGroup.querySelectorAll('.filter-choices__more').length, 1, 'Locale updates reuse the disclosure handler');
assert.equal(disclosure.textContent, 'Ещё (3)');
assert.equal(compactChoices[9].dataset.state, 'include', 'Locale and disclosure keep the active choice');
disclosure.click();
assert.equal(disclosure.textContent, 'Свернуть');
FilterChoice.enhanceGroup(compactGroup, { compactLimit: 6, moreLabel: 'More ({count})', lessLabel: 'Less' });
assert.equal(disclosure.getAttribute('aria-expanded'), 'true', 'Enhancing a group retains its expanded state');
FilterChoice.enhanceGroup(compactGroup);
assert.equal(compactGroup.querySelector('.filter-choices__more'), null);
assert.equal(compactGroup.querySelector('[data-filter-overflow]'), null, 'Removing compact mode restores all choices');
singleGroup.innerHTML = '<a href="#a" data-status="a">A</a><button data-status="b">B</button>';
let singleClicks = 0;
singleGroup.querySelector('button').addEventListener('click', () => singleClicks++);
FilterChoice.enhanceSingleGroup(singleGroup, { label: 'Statuses' });
FilterChoice.enhanceSingleGroup(singleGroup);
FilterChoice.syncSingleGroup(singleGroup, { value: 'b', attribute: 'data-status' });
singleGroup.querySelector('button').click();
assert.equal(singleClicks, 1, 'single-choice styling does not duplicate native handlers');
assert.equal(singleGroup.querySelector('button').getAttribute('aria-pressed'), 'true');
assert.equal(singleGroup.querySelector('button').dataset.state, undefined, 'single-choice never acquires tri-state cycle');
assert.equal(singleGroup.getAttribute('role'), null, 'navigation semantics retained');
FilterChoice.syncSingleGroup(singleGroup, { value: 'a', attribute: 'data-status' });
assert.equal(singleGroup.querySelector('a').getAttribute('aria-current'), 'true');

const from = document.getElementById('from');
const to = document.getElementById('to');
const bar = document.getElementById('bar');
let commits = [];
const range = RangeControl.enhance(from, to, { minGap: 0.5, fromLabel: 'Rating from', toLabel: 'Rating to', fromFieldLabel: 'Min', toFieldLabel: 'Max', fromDisplay: document.getElementById('fromDisplay'), toDisplay: document.getElementById('toDisplay'), rangeBar: bar, formatValue: value => value.toFixed(1), onCommit: (min, max) => commits.push([min, max]) });
assert.equal(RangeControl.enhance(from, to), range);
assert.equal(from.id, 'from', 'native IDs preserved');
assert.equal(range.numberFields.length, 2);
assert.equal(range.numberFields[0].parentElement.querySelector('span').textContent, 'Min');
assert.equal(range.numberFields[0].getAttribute('aria-label'), 'Rating from', 'numeric editor announces its filter context');
assert.equal(range.numberFields[1].getAttribute('aria-label'), 'Rating to');
assert.equal(range.numberFields[0].step, '0.1');
assert.equal(document.getElementById('fromDisplay').textContent, '7.0');
assert.equal(from.getAttribute('aria-valuemin'), '1');
assert.equal(from.getAttribute('aria-valuemax'), '9.5', 'Lower handle announces the active gap limit');
assert.equal(to.getAttribute('aria-valuemin'), '7.5', 'Upper handle announces the active gap limit');
assert.equal(from.getAttribute('aria-valuenow'), '7');
assert.equal(from.getAttribute('aria-valuetext'), '7.0');
RangeControl.enhance(from, to, { fromLabel: 'Рейтинг от', toLabel: 'Рейтинг до', fromFieldLabel: 'От', toFieldLabel: 'До' });
assert.equal(from.getAttribute('aria-label'), 'Рейтинг от', 'Idempotent enhancement refreshes localized labels');
assert.equal(range.numberFields[0].parentElement.querySelector('span').textContent, 'От', 'visible captions remain concise when accessible labels are descriptive');
assert.equal(range.numberFields[0].getAttribute('aria-label'), 'Рейтинг от', 'numeric editor accessible name follows the active locale');
assert.equal(range.numberFields[1].getAttribute('aria-label'), 'Рейтинг до');
assert.ok(parseFloat(bar.style.left) > 66 && parseFloat(bar.style.left) < 67);
assert.equal(commits.length, 0, 'initial synchronization is silent');
from.value = '9.9';
fire(from, 'input');
assert.equal(from.value, '9.5', 'preview clamps minimum gap without crossing');
assert.equal(commits.length, 0, 'preview does not persist');
fire(from, 'change');
fire(from, 'change');
assert.deepEqual(commits, [[9.5, 10]], 'changed range commits once');
assert.equal(to.getAttribute('aria-valuemin'), '10', 'Announced thumb bounds update after a range commit');
to.value = '2';
fire(to, 'input');
assert.equal(to.value, '10', 'upper cannot cross current lower bound');
fire(to, 'change');
assert.equal(commits.length, 1);
let nativeInputEvents = 0;
let nativeChangeEvents = 0;
from.addEventListener('input', () => nativeInputEvents++);
from.addEventListener('change', () => nativeChangeEvents++);
range.numberFields[0].value = '4.26';
fire(range.numberFields[0], 'change');
assert.equal(from.value, '4.3', 'numeric editor rounds to native step');
assert.equal(nativeInputEvents, 1);
assert.equal(nativeChangeEvents, 1);
assert.equal(commits.length, 2);
range.numberFields[0].focus();
range.numberFields[0].value = '5.26';
fire(range.numberFields[0], 'input');
assert.equal(from.value, '5.3', 'valid numeric input previews through original range');
assert.equal(range.numberFields[0].value, '5.26', 'typing draft is preserved until commit');
assert.equal(commits.length, 2);
fire(range.numberFields[0], 'change');
assert.equal(range.numberFields[0].value, '5.3');
assert.equal(commits.length, 3);
range.numberFields[0].value = '';
fire(range.numberFields[0], 'change');
assert.equal(from.value, '5.3', 'blank slider editor restores actual slider value');
assert.equal(commits.length, 3);
from.value = '6';
to.value = '8';
range.syncFromNative();
assert.equal(range.numberFields[0].value, '6');
assert.equal(commits.length, 3, 'saved state sync is silent');
from.disabled = true;
range.syncFromNative();
assert.equal(range.numberFields[0].disabled, true);

const numberFrom = document.getElementById('yearFrom');
const numberTo = document.getElementById('yearTo');
let numberCommits = [];
const numberRange = RangeControl.enhance(numberFrom, numberTo, { fromLabel: 'Year from', toLabel: 'Year to', onCommit: (min, max) => numberCommits.push([min, max]) });
assert.equal(numberRange.numberFields, undefined, 'native numeric pair adds no sliders or duplicates');
assert.equal(numberFrom.value, '');
assert.equal(numberTo.value, '');
numberFrom.value = '20';
fire(numberFrom, 'input');
assert.equal(numberFrom.value, '20', 'typing is not prematurely clamped');
fire(numberFrom, 'change');
assert.equal(numberFrom.value, '1900');
assert.deepEqual(numberCommits, [[1900, null]]);
numberTo.value = '1899';
fire(numberTo, 'change');
assert.equal(numberTo.value, '1900');
numberFrom.value = '';
fire(numberFrom, 'change');
assert.equal(numberFrom.value, '', 'numeric native range allows open boundary');
assert.deepEqual(numberCommits.at(-1), [null, 1900]);
numberRange.destroy();
assert.equal(numberFrom.getAttribute('aria-label'), null);
assert.equal(numberFrom.className, '');
const commitsBeforeDestroy = commits.length;
range.destroy();
assert.equal(document.querySelector('.filter-range__fields'), null);
assert.equal(from.classList.contains('filter-range__slider'), false);
from.value = '5';
fire(from, 'change');
assert.equal(commits.length, commitsBeforeDestroy, 'destroy removes persistence listeners');

