assert.match(css, /\.filter-choices\s*\{[^}]*flex-wrap:\s*wrap[^}]*overflow:\s*visible/s);
assert.match(css, /--filter-slider-thumb-size:\s*24px/, 'Slider target size meets the WCAG minimum target size');
assert.match(css, /filter-range > \.filter-range__slider::-webkit-slider-thumb\s*\{[^}]*width:\s*var\(--filter-slider-thumb-size\)/s);
assert.match(css, /filter-range > \.filter-range__slider::-moz-range-thumb\s*\{[^}]*width:\s*var\(--filter-slider-thumb-size\)/s);
assert.match(css, /filter-range > \.filter-range__slider:focus-visible\s*\{[^}]*outline:\s*2px solid[^}]*filter:\s*drop-shadow/s);
dom.window.close();
console.log('FilterControls: state cycle, group semantics, bounded numeric/range editing and cleanup passed');
